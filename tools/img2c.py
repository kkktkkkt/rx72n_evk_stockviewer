#!/usr/bin/env python3
"""img2c.py - 画像 -> RGB565 の Cソース(480x272)。

使い方:
  python3 tools/img2c.py --testpattern            # 合成パターン3種を src/app/img_00..02.c に出力(標準ライブラリのみ)
  python3 tools/img2c.py IN.png --index 1         # 画像を src/app/img_01.c に出力(Pillow が必要)
  --out-dir DIR で出力先を変更。

形式: 480x272、RGB565、uint16_t、リトルエンディアン(CPUの並びのまま)。
サイズが 480x272 でない画像は、拡大縮小せずエラー終了(終了コード 2)。
"""
import argparse
import os
import sys

W = 480
H = 272
PER_LINE = 16


def rgb565(r, g, b):
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


# ---- 合成テストパターン(標準ライブラリのみ) ----
def _fill(w, h, color):
    return [[color] * w for _ in range(h)]


def pattern0():
    """縦バー(赤・緑・青・白・黒) + 外周1pxの白枠 + 四隅の目印"""
    bars = [(255, 0, 0), (0, 255, 0), (0, 0, 255), (255, 255, 255), (0, 0, 0)]
    bw = W // len(bars)  # 96
    img = [[rgb565(*bars[min(x // bw, len(bars) - 1)]) for x in range(W)] for _ in range(H)]
    white = rgb565(255, 255, 255)
    for x in range(W):
        img[0][x] = white
        img[H - 1][x] = white
    for y in range(H):
        img[y][0] = white
        img[y][W - 1] = white
    m = 12  # 目印の大きさ: 左上=マゼンタ 右上=黄 左下=シアン 右下=橙
    marks = [
        (1, 1, (255, 0, 255)),
        (W - 1 - m, 1, (255, 255, 0)),
        (1, H - 1 - m, (0, 255, 255)),
        (W - 1 - m, H - 1 - m, (255, 128, 0)),
    ]
    for x0, y0, c in marks:
        v = rgb565(*c)
        for y in range(y0, y0 + m):
            for x in range(x0, x0 + m):
                img[y][x] = v
    return img


def pattern1():
    """水平グラデーション(赤->青) + 中央の十字線(2px白)"""
    img = []
    for _ in range(H):
        row = []
        for x in range(W):
            t = (255 * x) // (W - 1)
            row.append(rgb565(255 - t, 0, t))
        img.append(row)
    white = rgb565(255, 255, 255)
    for y in range(H):
        img[y][W // 2 - 1] = white
        img[y][W // 2] = white
    for x in range(W):
        img[H // 2 - 1][x] = white
        img[H // 2][x] = white
    return img


def pattern2():
    """32pxの格子 + 左半分=青系 / 右半分=緑系(タッチの左右判定の目視用)"""
    left = rgb565(0, 0, 128)
    right = rgb565(0, 96, 0)
    grid = rgb565(200, 200, 200)
    img = []
    for y in range(H):
        row = []
        for x in range(W):
            if (x % 32 == 0) or (y % 32 == 0):
                row.append(grid)
            else:
                row.append(left if x < W // 2 else right)
        img.append(row)
    return img


PATTERNS = [pattern0, pattern1, pattern2]


# ---- 画像ファイル(Pillow) ----
def load_image(path):
    try:
        from PIL import Image
    except ImportError:
        sys.stderr.write("エラー: Pillow がありません。pip install pillow\n")
        sys.exit(3)
    im = Image.open(path)
    if im.size != (W, H):
        sys.stderr.write("エラー: サイズ %dx%d は不可。%dx%d にしてください(自動で拡大縮小しません)\n"
                         % (im.size[0], im.size[1], W, H))
        sys.exit(2)
    im = im.convert("RGB")
    px = im.load()
    return [[rgb565(*px[x, y]) for x in range(W)] for y in range(H)]


# ---- C出力 ----
def write_c(img, index, out_dir, source):
    name = "g_img_%02d" % index
    path = os.path.join(out_dir, "img_%02d.c" % index)
    flat = [v for row in img for v in row]
    assert len(flat) == W * H
    lines = []
    lines.append("/* Generated by tools/img2c.py. 手で編集しない。 */")
    lines.append("/* source: %s / %dx%d RGB565 */" % (source, W, H))
    lines.append('#include "images.h"')
    lines.append("")
    lines.append("const uint16_t %s[APP_IMG_PIXELS] __attribute__((aligned(4))) = {" % name)
    for i in range(0, len(flat), PER_LINE):
        chunk = flat[i:i + PER_LINE]
        lines.append("    " + ",".join("0x%04X" % v for v in chunk) + ",")
    lines.append("};")
    lines.append("")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print("wrote %s (%d pixels)" % (path, len(flat)))


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    ap = argparse.ArgumentParser(description="画像 -> RGB565 Cソース(480x272)")
    ap.add_argument("input", nargs="?", help="入力画像(PNG/JPG)")
    ap.add_argument("--index", type=int, default=0, help="出力番号 NN (img_NN.c)")
    ap.add_argument("--testpattern", action="store_true", help="合成パターン3種を img_00..02 に出力")
    ap.add_argument("--out-dir", default=os.path.join(here, "..", "src", "app"))
    a = ap.parse_args()

    out_dir = os.path.normpath(a.out_dir)
    if a.testpattern:
        for i, fn in enumerate(PATTERNS):
            write_c(fn(), i, out_dir, "testpattern %d (%s)" % (i, fn.__name__))
        return 0
    if not a.input:
        ap.error("入力画像か --testpattern を指定してください")
    if not (0 <= a.index <= 99):
        ap.error("--index は 0〜99")
    write_c(load_image(a.input), a.index, out_dir, os.path.basename(a.input))
    return 0


if __name__ == "__main__":
    sys.exit(main())
